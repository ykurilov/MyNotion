    private static func rowsAction(_ invocation: String, _ summary: String) -> CommandSpec {
        .command(invocation, summary, access: .write, batchable: true, stage: 4, example: "mynotion \(invocation) Задачи Отчёт",
                 arguments: [database, .positional("rows", .row, "Строки: id или названия", repeated: true)])
    }

    private static func relationAction(_ invocation: String, _ summary: String) -> CommandSpec {
        .command(invocation, summary, access: .write, batchable: true, stage: 4,
                 example: "mynotion \(invocation) Задачи Отчёт Проект --to 'Сайт'",
                 arguments: [database, row, property, .flag("to", .row, "Строки связанной базы", required: true, repeated: true)])
    }
}
