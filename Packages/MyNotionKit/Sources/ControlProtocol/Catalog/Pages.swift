import Foundation

/// Страницы и корзина (этап 2, US1).
extension CommandCatalog {
    static let pages: [CommandSpec] = [
        .command("page tree", "Дерево страниц от корня или от страницы", access: .read, stage: 2, example: "mynotion page tree --depth 2",
                 arguments: [.positional("page", .page, "С какой страницы", required: false), .flag("depth", .int, "Глубина")]),
        .command("page get", "Свойства страницы: путь, иконка, обложка, родитель, тип, даты", access: .read, stage: 2,
                 example: "mynotion page get Проекты/Встреча", arguments: [.positional("page", .page, "Страница")]),
        .command("page read", "Содержимое страницы в Markdown или JSON блоков", access: .read, stage: 2,
                 example: "mynotion page read current --format json",
                 arguments: [.positional("page", .page, "Страница"),
                             .flag("format", .choice(["markdown", "json"]), "Вид ответа", default: "markdown"),
                             .switch("withChildren", "С подстраницами")]),
        .command("page create", "Новая страница: в корне или в родителе, из шаблона, с Markdown", access: .write, batchable: true, stage: 2,
                 example: "mynotion page create --parent Проекты --title 'Встреча 24.10' --markdown notes.md",
                 arguments: [.flag("parent", .page, "Родитель; без него — в корне"), .flag("title", .string, "Название", required: true),
                             .flag("icon", .string, "Эмодзи"), .flag("after", .page, "За какой соседней страницей"),
                             .flag("template", .page, "Шаблон"), .flag("markdown", .content, "Содержимое: файл или - (stdin)")]),
        .command("page write", "Заменить содержимое страницы Markdown-текстом", access: .write, batchable: true, stage: 2,
                 example: "cat notes.md | mynotion page write Проекты/Встреча --markdown -",
                 arguments: [.positional("page", .page, "Страница"), .flag("markdown", .content, "Файл или - (stdin)", required: true)]),
        .command("page append", "Дописать Markdown в конец страницы или за блоком", access: .write, batchable: true, stage: 2,
                 example: "echo '- [ ] позвонить' | mynotion page append current --markdown -",
                 arguments: [.positional("page", .page, "Страница"), .flag("markdown", .content, "Файл или - (stdin)", required: true),
                             .flag("after", .block, "За каким блоком")]),
        .command("page rename", "Переименовать страницу", access: .write, batchable: true, stage: 2,
                 example: "mynotion page rename current --title 'Итоги'",
                 arguments: [.positional("page", .page, "Страница"), .flag("title", .string, "Новое название", required: true)]),
        .command("page move", "Перенести страницу к другому родителю или в корень", access: .write, batchable: true, stage: 2,
                 example: "mynotion page move Встреча --parent Архив --first",
                 arguments: [.positional("page", .page, "Страница"), .flag("parent", .page, "Новый родитель"),
                             .switch("root", "В корень"), .flag("after", .page, "За какой соседней страницей"),
                             .switch("first", "Первой среди соседей")],
                 exclusive: [["parent", "root"], ["after", "first"]], requiresOneOf: [["parent", "root"]]),
        .command("page duplicate", "Копия страницы с подстраницами", access: .write, stage: 2, example: "mynotion page duplicate Шаблон",
                 arguments: [.positional("page", .page, "Страница")]),
        .command("page trash", "Убрать страницу в корзину", access: .write, batchable: true, stage: 2,
                 example: "mynotion page trash Черновик", arguments: [.positional("page", .page, "Страница")]),
        .command("page restore", "Вернуть страницу из корзины", access: .write, batchable: true, stage: 2,
                 example: "mynotion page restore Черновик --include-trashed", arguments: [.positional("page", .page, "Страница")]),
        .command("page layout", "Широкая страница и мелкий шрифт", access: .write, batchable: true, stage: 2,
                 example: "mynotion page layout current --full-width on",
                 arguments: [.positional("page", .page, "Страница"), .flag("fullWidth", .onOff, "Широкая"),
                             .flag("smallText", .onOff, "Мелкий шрифт")],
                 requiresOneOf: [["fullWidth", "smallText"]]),
        .command("page share", "Ссылка на страницу для чтения в браузере: включить, выключить, сменить, показать", access: .write,
                 stage: 8, example: "mynotion page share on current --subpages off",
                 arguments: [.positional("action", .choice(["on", "off", "rotate", "show"]), "on, off, rotate или show"),
                             .positional("page", .page, "Страница"), .flag("subpages", .onOff, "Вместе с подстраницами (по умолчанию да)")]),
        .command("trash list", "Страницы в корзине", access: .read, stage: 2, example: "mynotion trash list"),
        .command("trash delete", "Удалить страницу из корзины навсегда", access: .write, stage: 2,
                 example: "mynotion trash delete Черновик --force",
                 arguments: [.positional("page", .page, "Страница в корзине"), .switch("force", "Подтверждение: удаление без возврата")]),
        .command("trash empty", "Очистить корзину навсегда", access: .write, stage: 2, example: "mynotion trash empty --force",
                 arguments: [.switch("force", "Подтверждение: удаление без возврата")]),
    ]
}
